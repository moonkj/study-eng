/// 목표 난이도와 영역에 가장 가까운, 아직 안 쓴 문항을 고른다.
LevelTestItem pickTestItem(int step, Skill skill, Set<LevelTestItem> used) {
  final candidates = levelTestPool.where((i) => !used.contains(i)).toList();
  candidates.sort((a, b) {
    int cost(LevelTestItem i) => (i.step - step).abs() * 2 + (i.skill == skill ? 0 : 3);
    return cost(a).compareTo(cost(b));
  });
  return candidates.first;
}
